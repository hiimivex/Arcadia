static bool trOn() { static int on = -1; if (on < 0) { const char* l = std::getenv("ARCADIA_LANG"); on = (l && !std::strncmp(l, "en", 2)) ? 1 : 0; } return on == 1; }
static std::string trStr(const std::string& s, int depth = 0) {
  static std::unordered_map<std::string, std::string> ex;
  if (ex.empty()) for (auto& e : TR_EX) ex.emplace(e[0], e[1]);
  auto it = ex.find(s); if (it != ex.end()) return it->second;
  if (depth > 2) return s;
  for (auto& p : TR_PRE) { size_t n = std::strlen(p[0]); if (s.size() > n && !s.compare(0, n, p[0])) return std::string(p[1]) + trStr(s.substr(n), depth + 1); }
  for (auto& p : TR_SUF) { size_t n = std::strlen(p[0]); if (s.size() > n && !s.compare(s.size() - n, n, p[0])) return trStr(s.substr(0, s.size() - n), depth + 1) + p[1]; }
  return s;
}
// Renvoie un pointeur stable (cache) vers la traduction ; identique si FR.
static const char* TR(const char* s) {
  if (!s || !*s || !trOn()) return s;
  static std::unordered_map<std::string, std::string> cache;
  auto it = cache.find(s); if (it != cache.end()) return it->second.c_str();
  if (cache.size() > 4096) cache.clear();
  return cache.emplace(s, trStr(s)).first->second.c_str();
}
