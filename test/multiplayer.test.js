const assert = require('assert');
const { lookup, ipDigits } = require('../src/multiplayer');
const t = (c, s) => lookup(c, s);
assert.deepStrictEqual(t('PSP', 'Monster Hunter Freedom (Europe)').modes.map(m => [m.type, m.players, m.ready]), [['adhoc', 4, true]]);
assert.strictEqual(t('PSP', "Syphon Filter - Logan's Shadow (Europe) (En,Fr)").modes[0].players, 8);
assert.strictEqual(t('PSP', 'Medal of Honor - Heroes 2 (USA)').modes[0].players, 16);
assert.strictEqual(t('3DS', 'Mario Kart 7 (Rev 2)').modes[0].type, 'wireless');
assert.deepStrictEqual(t('SWITCH', "Luigi’s Mansion 3[0100DCA0064A6000][US][v0]").modes.map(m => m.type), ['couch', 'ldn']);
assert.deepStrictEqual(t('SWITCH', "Super Mario 3D World + Bowser's Fury").modes.map(m => m.type), ['couch', 'ldn']);
assert.strictEqual(t('SWITCH', 'Super Mario Bros. 35').modes[0].ready, false);
assert.strictEqual(t('PSP', 'God of War - Ghost of Sparta (Europe)').solo, true);
assert.strictEqual(t('PSP', 'Jeu Inconnu').known, false);
assert.strictEqual(t('DS', 'Call of Duty - Black Ops (USA)').modes[0].ready, false);
const d = ipDigits('82.65.1.20');
assert.strictEqual(Object.values(d).join(''), '082065001020');
assert.strictEqual(d.ppsspp_pro_ad_hoc_server_address12, '0');
assert.strictEqual(ipDigits('300.1.1.1'), null);
